def colormap_names():
    """Names of the built-in colour maps (as used in an image's color_table)."""
    return list(COLORMAP_STOPS)


def colormap_rgb(name, count=256):
    """The built-in colour map `name` as `count` (r, g, b) tuples, 0-1, linearly interpolated between its stops; None for an unknown name."""
    stops = COLORMAP_STOPS.get(name)
    if stops is None or count < 2:
        return None
    last = len(stops) - 1
    out = []
    for i in range(count):
        pos = i * last / (count - 1)
        lo = min(int(pos), last - 1)
        frac = pos - lo
        a, b = stops[lo], stops[lo + 1]
        out.append(tuple(a[k] + (b[k] - a[k]) * frac for k in range(3)))
    return out

